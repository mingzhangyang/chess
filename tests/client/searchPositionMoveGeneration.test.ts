import test from 'node:test';
import assert from 'node:assert/strict';
import { Chess, type Move } from 'chess.js';
import { SearchPosition, squareFromAlgebraic, squareToAlgebraic, type SearchMove } from '../../src/utils/chess-ai/searchPosition';

const INITIAL = new Chess().fen();
const KIWIPETE = 'r3k2r/p1ppqpb1/bn2pnp1/3PN3/1p2P3/2N2Q1p/PPPBBPPP/R3K2R w KQkq - 0 1';
const ENDGAME = '8/2p5/3p4/KP5r/1R3p1k/8/4P1P1/8 w - - 0 1';
const uci = (move: SearchMove) => `${squareToAlgebraic(move.from)}${squareToAlgebraic(move.to)}${move.promotion ?? ''}`;
const referenceUci = (move: Pick<Move, 'from' | 'to' | 'promotion'>) => `${move.from}${move.to}${move.promotion ?? ''}`;
const move = (value: string): SearchMove => ({ from: squareFromAlgebraic(value.slice(0, 2)), to: squareFromAlgebraic(value.slice(2, 4)), promotion: value[4] as SearchMove['promotion'] });
const snapshot = (p: SearchPosition) => ({
  board: Array.from({ length: 64 }, (_, i) => p.pieceAt(i)),
  fen: p.toFen({ rawEnPassant: true }), normalized: p.toFen(), turn: p.turn,
  rights: p.castlingRights, ep: p.enPassantSquare, halfmove: p.halfmoveClock,
  fullmove: p.fullmoveNumber, material: p.materialBalance, hash: p.positionHash,
  repetitionCount: p.repetitionCount, repetitionStatus: p.repetitionStatus,
  ply: p.ply, check: p.isInCheck(),
});
const compare = (p: SearchPosition, game: Chess, label: string) => {
  const before = snapshot(p);
  const actual = p.generateLegalMoves().map(uci).sort();
  const refMoves = game.moves({ verbose: true });
  const expected = refMoves.map(referenceUci).sort();
  assert.deepEqual(actual, expected, label);
  assert.equal(new Set(actual).size, actual.length, `${label}: duplicates`);
  const tactical = refMoves.filter((m) => m.isCapture() || m.isEnPassant() || m.isPromotion()).map(referenceUci).sort();
  assert.deepEqual(p.generateTacticalMoves().map(uci).sort(), tactical, `${label}: tactical`);
  assert.deepEqual(p.generateQuiescenceMoves().map(uci).sort(), p.isInCheck() ? expected : tactical, `${label}: quiescence`);
  assert.deepEqual(snapshot(p), before, `${label}: generation restores state`);
};

// Each recursion level is generated by the new position, not chess.js.
const perft = (p: SearchPosition, depth: number): number => {
  if (depth === 0) return 1;
  let count = 0;
  for (const candidate of p.generateLegalMoves()) {
    p.makeMove(candidate);
    try { count += perft(p, depth - 1); } finally { p.undo(); }
  }
  return count;
};

test('fixed edge positions agree with the public chess.js legal-move API', () => {
  const fens = [
    INITIAL, KIWIPETE, ENDGAME,
    '4r1k1/8/8/8/8/8/4N3/4K3 w - - 0 1', // pinned knight
    '4r1k1/8/8/8/1b6/8/8/R3K3 w - - 0 1', // double check
    'r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1',
    'r3k2r/8/8/8/8/8/8/R3K2R b KQkq - 0 1',
    'r3k2r/8/8/8/8/5r2/8/R3K2R w KQkq - 0 1', // attacked transit
    'r3k2r/8/8/8/8/6r1/8/R3K2R w KQkq - 0 1', // attacked destination
    'r3k2r/8/8/8/8/8/8/R2BK2R w KQkq - 0 1', // blocked queenside
    '4k3/4n3/8/3K4/8/8/8/4R3 w - - 0 1', // pinned knight still attacks the king
    '4k3/8/8/3pP3/8/8/8/4K3 w - d6 0 1',
    '4k3/8/8/8/3pP3/8/8/4K3 b - e3 0 1',
    '4r1k1/8/8/3pP3/8/8/8/4K3 w - d6 0 2', // pinned EP
    '8/6bb/8/8/R1pP2k1/4P3/P7/K7 b - d3 0 1', // EP opens rank
    '6k1/8/8/3pP3/4K3/8/8/8 w - d6 0 2', // EP evades check
    '1r2k3/P7/8/8/8/8/8/4K3 w - - 98 1',
    '4k3/8/8/8/8/8/p7/1R2K3 b - - 0 1',
    '7k/5Q2/6K1/8/8/8/8/8 b - - 0 1', // stalemate
    '7k/6Q1/6K1/8/8/8/8/8 b - - 0 1', // mate
  ];
  for (const fen of fens) compare(new SearchPosition(fen, { historyComplete: true }), new Chess(fen), fen);
});

test('special moves, check evasions and king captures are classified correctly', () => {
  const moves = (fen: string) => new SearchPosition(fen).generateLegalMoves().map(uci);
  const promotion = new SearchPosition('1r2k3/P7/8/8/8/8/8/4K3 w - - 0 1');
  for (const suffix of ['n', 'b', 'r', 'q']) {
    assert.ok(promotion.generateTacticalMoves().map(uci).includes(`a7a8${suffix}`));
    assert.ok(promotion.generateTacticalMoves().map(uci).includes(`a7b8${suffix}`));
  }
  const epPinned = moves('8/6bb/8/8/R1pP2k1/4P3/P7/K7 b - d3 0 1');
  assert.ok(!epPinned.includes('c4d3'));
  const evasion = new SearchPosition('6k1/8/8/3pP3/4K3/8/8/8 w - d6 0 2');
  assert.ok(evasion.generateTacticalMoves().map(uci).includes('e5d6'));
  assert.ok(evasion.generateQuiescenceMoves().length > evasion.generateTacticalMoves().length);
  const doubleCheck = moves('4r1k1/8/8/8/1b6/8/8/R3K3 w - - 0 1');
  assert.ok(doubleCheck.length > 0 && doubleCheck.every((m) => m.startsWith('e1')));
  assert.ok(!moves('4k3/8/8/8/8/8/8/4R1K1 w - - 0 1').includes('e1e8'), 'never capture the opponent king');
  assert.ok(!moves('4k3/8/8/8/8/8/8/4K3 w KQ - 0 1').some((m) => m === 'e1g1' || m === 'e1c1'), 'castling requires a rook');
});

test('seeded legal games match complete and tactical move sets at every position', () => {
  let seed = 0x9ab31e71;
  const random = (n: number) => { seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5; return (seed >>> 0) % n; };
  let visited = 0;
  for (let run = 0; run < 8; run++) {
    const game = new Chess();
    const p = new SearchPosition(INITIAL, { historyComplete: true });
    const stack: ReturnType<typeof snapshot>[] = [];
    for (let ply = 0; ply < 70; ply++) {
      compare(p, game, `game ${run} ply ${ply} ${game.fen()}`);
      visited++;
      const reference = game.moves({ verbose: true });
      if (!reference.length) break;
      const selected = reference[random(reference.length)];
      stack.push(snapshot(p));
      p.makeMove(move(referenceUci(selected)));
      game.move({ from: selected.from, to: selected.to, promotion: selected.promotion });
      assert.equal(p.toFen(), game.fen());
      assert.equal(p.positionHash, new SearchPosition(p.toFen({ rawEnPassant: true })).positionHash);
    }
    while (stack.length) { p.undo(); game.undo(); assert.deepEqual(snapshot(p), stack.pop()); }
  }
  assert.ok(visited >= 400);
});

test('independent perft matches published positions without draw adjudication', () => {
  for (const [fen, depth, expected] of [[INITIAL, 4, 197281], [KIWIPETE, 3, 97862], [ENDGAME, 4, 43238]] as const) {
    const p = new SearchPosition(fen, { historyComplete: true });
    const before = snapshot(p);
    assert.equal(perft(p, depth), expected, fen);
    assert.deepEqual(snapshot(p), before);
  }
  const cycle = ['g1f3', 'g8f6', 'f3g1', 'f6g8'];
  const repeated = SearchPosition.fromHistory(INITIAL, [...cycle, ...cycle].map(move), { historyComplete: true });
  assert.equal(repeated.repetitionStatus, 'threefold');
  assert.equal(perft(repeated, 2), 400, 'perft must not stop on repetition');
  assert.equal(perft(new SearchPosition(INITIAL.replace('0 1', '100 1')), 2), 400, 'perft must not stop on the 50-move rule');
});

test('all fields and prior repetition history survive multi-ply generation and undo', () => {
  const cycle = ['g1f3', 'g8f6', 'f3g1', 'f6g8'];
  const p = SearchPosition.fromHistory(INITIAL, cycle.map(move), { historyComplete: true });
  const walk = (depth: number) => {
    const before = snapshot(p);
    const candidates = p.generateLegalMoves();
    assert.deepEqual(snapshot(p), before);
    if (depth) for (const candidate of candidates) {
      p.makeMove(candidate);
      walk(depth - 1);
      p.undo();
      assert.deepEqual(snapshot(p), before);
    }
  };
  walk(2);
  for (const value of cycle) p.makeMove(move(value));
  assert.equal(p.repetitionCount, 3, 'prior occurrences survive trials');
  p.restore(0);
  assert.equal(p.repetitionCount, 2);
});

test('trial-board changes unwind when attack detection throws for special moves', () => {
  const cases: Array<[string, Array<[string, number]>]> = [
    ['4k3/8/8/3pP3/8/8/8/4K3 w - d6 0 1', [['e5', 0], ['d5', 0], ['d6', 1]]],
    // A pinned pawn out of check: its capturing promotion still needs a trial.
    ['rb2k3/P7/8/K7/8/8/8/8 w - - 0 1', [['a7', 0], ['b8', 5]]],
    ['r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1', [['e1', 0], ['g1', 6], ['h1', 0], ['f1', 4]]],
  ];
  for (const [fen, expected] of cases) {
    const p = new SearchPosition(fen, { historyComplete: true });
    const before = snapshot(p);
    const internal = p as unknown as { isSquareAttacked: (...args: unknown[]) => boolean };
    const original = internal.isSquareAttacked;
    internal.isSquareAttacked = (...args) => {
      if (expected.every(([square, piece]) => p.pieceAt(squareFromAlgebraic(square)) === piece)) {
        throw new Error('injected attack error');
      }
      return original.apply(p, args);
    };
    try { assert.throws(() => p.generateLegalMoves(), /injected attack error/, fen); }
    finally { internal.isSquareAttacked = original; }
    assert.deepEqual(snapshot(p), before, fen);
    assert.equal(p.repetitionCount, 1);
  }
});

test('pinned pieces move only along the pin line and unpinned pieces skip no legal move', () => {
  const fens = [
    '4k3/8/8/8/8/2b5/3B4/4K3 w - - 0 1', // bishop pinned on its own diagonal
    '4k3/4r3/8/8/8/8/4R3/4K3 w - - 0 1', // rook pinned on its own file
    '4k3/8/8/1b6/8/3Q4/8/5K2 w - - 0 1', // queen pinned diagonally
    '4k3/4q3/8/8/8/8/4Q3/4K3 w - - 0 1', // queen pinned on a file
    '4k3/8/8/8/8/5b2/4P3/3K4 w - - 0 1', // pawn pinned diagonally, can capture the pinner
    '4k3/4r3/8/8/8/8/4P3/4K3 w - - 0 1', // pawn pinned on a file, can still push
    '4k3/8/8/8/1b6/8/3P4/4K3 w - - 0 1', // pawn pinned diagonally, cannot push
    'k7/8/8/3q4/8/8/8/K2R4 w - - 0 1', // no pin: piece beside the king on another line
    '4k3/8/8/8/8/8/8/r2NK3 w - - 0 1', // knight pinned on the first rank
    '4k3/8/4r3/8/4B3/8/8/4K3 w - - 0 1', // bishop pinned on a file has no move
    'K7/1P6/8/8/8/8/6q1/k7 w - - 0 1', // pinned pawn on the long diagonal
    '3k4/8/8/2KPp2r/8/8/8/8 w - e6 0 1', // en passant would expose the king
  ];
  for (const fen of fens) compare(new SearchPosition(fen), new Chess(fen), fen);
});

test('random middlegames match complete and tactical move sets', () => {
  let seed = 0x3a71c0de;
  const random = (n: number) => { seed = (Math.imul(seed, 1103515245) + 12345) >>> 0; return (seed >>> 8) % n; };
  let checked = 0;
  for (let gameIndex = 0; gameIndex < 30; gameIndex++) {
    const game = new Chess();
    for (let ply = 0; ply < 70 && !game.isGameOver(); ply++) {
      const moves = game.moves({ verbose: true });
      game.move(moves[random(moves.length)]);
      if (ply >= 10) { compare(new SearchPosition(game.fen()), game, `game ${gameIndex} ply ${ply}`); checked++; }
    }
  }
  assert.ok(checked > 1000);
});

test('hasLegalMove agrees with full generation, including mate, stalemate and double check', () => {
  for (const fen of [
    INITIAL, KIWIPETE, ENDGAME,
    '7k/5Q2/6K1/8/8/8/8/8 b - - 0 1', // stalemate
    '7k/6Q1/6K1/8/8/8/8/8 b - - 0 1', // checkmate
    '4r1k1/8/8/8/1b6/8/8/R3K3 w - - 0 1', // double check
    'k7/8/8/8/8/8/1r6/K1r5 w - - 0 1', // mate by rooks
  ]) {
    const p = new SearchPosition(fen);
    assert.equal(p.hasLegalMove(), p.generateLegalMoves().length > 0, fen);
    assert.equal(p.hasLegalMove(), new Chess(fen).moves().length > 0, fen);
  }
});
